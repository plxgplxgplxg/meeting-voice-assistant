"""Export the public OpenAPI contract of the backend to docs/04-design/api-specification.yaml.

Run from ``backend-api``::

    python scripts/export_openapi.py
"""

import json
import sys
from pathlib import Path
from typing import Any

import yaml

BACKEND_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND_ROOT))

from app.main import app  # noqa: E402

SPEC_PATH = BACKEND_ROOT.parent / "docs" / "04-design" / "api-specification.yaml"


def build_spec() -> dict[str, Any]:
    """Return the application's OpenAPI document as plain JSON-compatible data.

    Returns:
        The schema generated by FastAPI, round-tripped through JSON so it compares
        equal to a document loaded back from YAML.
    """
    return json.loads(json.dumps(app.openapi()))


def render_spec(spec: dict[str, Any]) -> str:
    """Serialise the document to deterministic YAML text.

    Args:
        spec: OpenAPI document.

    Returns:
        YAML text with stable key order and unicode preserved.
    """
    return yaml.safe_dump(spec, sort_keys=True, allow_unicode=True, width=100)


def main() -> None:
    """Write the specification file."""
    SPEC_PATH.write_text(render_spec(build_spec()), encoding="utf-8")
    print(f"wrote {SPEC_PATH}")


if __name__ == "__main__":
    main()
