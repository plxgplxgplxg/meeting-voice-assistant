from typing import Any

import httpx
import structlog

from app.core.config import ai_settings
from app.core.errors import ProviderError, ProviderNotConfiguredError
from app.rag.protocols import LLMClientProtocol

logger = structlog.get_logger(__name__)


class OpenAICompatibleLLMClient(LLMClientProtocol):
    """LLM client for OpenAI-compatible APIs (Google Gemini 2.0 Flash and OpenAI GPT-4o-mini).

    Implements LLMClientProtocol with clean error propagation and configurable timeout.
    """

    def __init__(
        self,
        provider: str | None = None,
        api_key: str | None = None,
        timeout: float = 45.0,
        client: httpx.AsyncClient | None = None,
    ) -> None:
        """Initialize LLM client.

        Args:
            provider: LLM provider name ('gemini' or 'openai'). Defaults to ai_settings.llm_provider.
            api_key: Secret API key. Defaults to settings corresponding to selected provider.
            timeout: HTTP request timeout in seconds.
            client: Optional injected httpx.AsyncClient instance for connection reuse/mocking.
        """
        self.provider = (provider or ai_settings.llm_provider).lower()
        self.api_key = api_key or (
            ai_settings.gemini_api_key
            if self.provider == "gemini"
            else ai_settings.openai_api_key
        )
        self.timeout = timeout
        self._client = client

    @property
    def is_available(self) -> bool:
        """Indicate whether the client has an API key configured.

        Returns:
            True if api_key is present, False otherwise.
        """
        return bool(self.api_key and self.api_key.strip())

    @property
    def endpoint(self) -> str:
        """API endpoint URL according to selected provider."""
        if self.provider == "gemini":
            return "https://generativelanguage.googleapis.com/v1beta/openai/chat/completions"
        return "https://api.openai.com/v1/chat/completions"

    @property
    def model_name(self) -> str:
        """Default model name for the provider."""
        if self.provider == "gemini":
            return "gemini-2.0-flash"
        return "gpt-4o-mini"

    async def generate_chat_completion(
        self,
        messages: list[dict[str, str]],
        temperature: float = 0.2,
    ) -> str:
        """Generate a chat completion response from the language model.

        Args:
            messages: List of chat messages containing 'role' and 'content'.
            temperature: Sampling temperature for generation.

        Returns:
            String response content generated by the model.

        Raises:
            ProviderNotConfiguredError: If no API key is configured for the provider.
            ProviderError: If the HTTP request fails or the payload is invalid.
        """
        if not self.is_available:
            raise ProviderNotConfiguredError(
                f"LLM provider not configured: {self.provider}"
            )

        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }

        payload: dict[str, Any] = {
            "model": self.model_name,
            "messages": messages,
            "temperature": temperature,
        }

        try:
            if self._client is not None:
                response = await self._client.post(
                    self.endpoint, headers=headers, json=payload, timeout=self.timeout
                )
            else:
                async with httpx.AsyncClient(timeout=self.timeout) as client:
                    response = await client.post(self.endpoint, headers=headers, json=payload)
        except httpx.HTTPError as exc:
            raise ProviderError(f"LLM request failed: {exc}") from exc

        if response.status_code != 200:
            logger.error(
                "llm_api_call_failed",
                provider=self.provider,
                status_code=response.status_code,
                body=response.text,
            )
            raise ProviderError(f"LLM API request failed with status {response.status_code}")

        data = response.json()
        choices = data.get("choices", [])
        if not choices:
            raise ProviderError("LLM API returned response with empty choices")

        content = choices[0].get("message", {}).get("content", "")
        return str(content)
